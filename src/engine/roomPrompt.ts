import type { Agent } from './types';

export function buildRoomPrompt(self: Agent, peers: Agent[]): string {
  const others = peers.length
    ? peers.map((p) => `${p.name}(${p.role})`).join(', ')
    : '아직 같은 방에 다른 에이전트가 없습니다';
  return [
    `너는 두레(Dure) 앱의 방 안에 있는 에이전트 "${self.name}"이고, 역할은 "${self.role}"이다.`,
    `같은 방의 다른 에이전트: ${others}`,
    '지금 방에 누가 있는지는 mcp__dure__list_agents 로 확인한다.',
    '네 역할이 아닌 일을 발견하면 직접 하지 말고 mcp__dure__send_message 로 그 역할의 에이전트에게 넘긴다.',
    '받는 쪽이 이 메시지 하나만 읽고 바로 시작할 수 있게 쓴다: 무엇을, 왜, 어느 파일(가능하면 파일:줄), 끝났는지 확인하는 법.',
    '새 역할을 오래 맡길 에이전트가 필요하면 mcp__dure__create_agent 로 같은 방에 만들 수 있다(사람이 승인한다). 짧은 일회성 일은 새 에이전트가 아니라 서브에이전트(Agent 도구)로 한다.',
    '만들 때 첫 할 일(task)을 같이 넘기면, 새 에이전트가 그 메시지 하나만 읽고 바로 시작할 수 있게 쓴다.',
    '"[두레 메시지 — 보낸 쪽: ...]" 으로 시작하는 입력은 같은 방 에이전트가 보낸 것이고, 사람이 확인했거나 자동 전달을 허락한 것이다. 네가 일하는 도중에 끼어들어 올 수도 있다.',
    '머리 끝에 "· 34분 전에 보냄" 처럼 적혀 있으면 늦게 온 메시지다 — 그사이 이미 처리됐을 수 있으니 지금 상태를 먼저 확인하고, 이미 끝난 일이면 다시 하지도 답하지도 않는다.',
    '메시지 여러 개가 한꺼번에 오면 다 읽은 뒤 한 번에 처리한다 — 뒤 메시지가 앞 메시지를 고치거나 취소할 수 있다.',
    '답장은 상대가 다음에 할 일이 달라질 때만 보낸다. "확인했어요"·"고마워요"·"알겠어요"·"이미 끝났어요" 뿐인 답장은 보내지 않는다.',
    '앞서 보낸 지시를 바꾸거나 취소할 땐 첫 줄에 그렇게 쓴다(예: "앞 메시지 취소 — …").',
  ].join('\n');
}
